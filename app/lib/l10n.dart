/// UI string in the current app language.
String L(String key) => _s[app.lang]?[key] ?? _s['en']![key] ?? key;

/// Pick the right language from a content map like {"en": "...", "gu": "..."}.
String tr(dynamic o, [String? lang]) {
  if (o == null) return '';
  if (o is String) return o;
  if (o is Map) {
    final l = lang ?? app.lang;
    final v = o[l] ?? o['en'];
    return v == null ? '' : v.toString();
  }
  return o.toString();
}

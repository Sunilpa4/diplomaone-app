def fixed():
    b = title("Fixed Partitions: Internal Fragmentation") + HATCH
    alloc = dict((i, j) for j, i in M.fit_fixed(JOBS, PARTS, "first") if i is not None)
    x, w, y = 70, 150, 36
    b += mem_block(x, y, w, 30, "Operating system", PF, P); y += 30
    hs = [32, 60, 36, 84, 40]
    for i, (ps, h) in enumerate(zip(PARTS, hs)):
        b += box(x, y, w, h, "#fff", INK, 0, 1.4)
        b += text(x - 6, y + h / 2, f"{ps} KB", 9, anchor="end", weight="bold", color=GREY)
        if i in alloc:
            j = alloc[i]
            used = max(14, h * JOBS[j] / ps)
            b += box(x, y, w, used, GREENF, GREEN, 0, 1.2) + text(x + w / 2, y + used / 2, f"J{j + 1} = {JOBS[j]} KB", 9, weight="bold", color=GREEN)
            if h - used > 12:
                b += hatch(x, y + used, w, h - used, f"{ps - JOBS[j]} KB waste")
            b += text(x + w + 6, y + h / 2, f"wasted {ps - JOBS[j]}", 8.8, anchor="start", color="#8A6400", weight="bold")
        else:
            b += text(x + w / 2, y + h / 2, "free (too small for J5)", 8.8, color=GREY)
        y += h
    waste = sum(PARTS[i] - JOBS[j] for i, j in alloc.items())
    b += text(180, y + 16, f"Total internal fragmentation = {waste} KB", 10, weight="bold", color="#8A6400")
    b += note(12, y + 30, 336, ["Memory is divided into fixed partitions at boot time.", "Each partition holds exactly one process (MFT).",
                                "Space left inside a partition is wasted: internal", "fragmentation. Degree of multiprogramming = partitions."], size=9.6)
    return svg(360, y + 102, b)



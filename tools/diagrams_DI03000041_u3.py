def fit():
    b = title("First, Best and Worst Fit (Practical 3)")
    meths = [("First fit", "first", GREEN, GREENF), ("Best fit", "best", BLUE, BLUEF), ("Worst fit", "worst", ORANGE, ORANGEF)]
    b += text(180, 34, "Jobs: J1 20, J2 200, J3 500, J4 50, J5 150 KB", 9.4, color=GREY, weight="bold")
    for k, (nm, m, c, f) in enumerate(meths):
        x = 12 + k * 114
        b += text(x + 53, 54, nm, 10.5, weight="bold", color=c)
        res = M.fit_fixed(JOBS, PARTS, m)
        alloc = {i: j for j, i in res if i is not None}
        for i, ps in enumerate(PARTS):
            y = 64 + i * 40
            if i in alloc:
                j = alloc[i]
                b += box(x, y, 106, 36, f, c, 4, 1.3) + text(x + 53, y + 11, f"{ps} KB", 9, color=GREY)
                b += text(x + 53, y + 25, f"J{j + 1} ({JOBS[j]}), waste {ps - JOBS[j]}", 8.4, weight="bold", color=c)
            else:
                b += box(x, y, 106, 36, "#fff", "#BBB", 4, 1.2) + text(x + 53, y + 11, f"{ps} KB", 9, color=GREY) + text(x + 53, y + 25, "free", 8.6, color=GREY)

def replace_grid(algo, ttl):
    steps, faults = M.replace(REFS, 4, algo)
    b = title(ttl)
    x0, cw, rh, y0 = 46, 25, 22, 40
    b += text(x0 - 6, y0 + rh / 2, "Ref", 9, anchor="end", weight="bold", color=P)
    for k, (r, fr, fault, victim) in enumerate(steps):
        x = x0 + k * cw
        b += box(x, y0, cw, rh, PF, P, 0, 1) + text(x + cw / 2, y0 + rh / 2, str(r), 10, weight="bold", color=P)
        for s in range(4):
            y = y0 + rh * (s + 1) + 4
            v = fr[s] if s < len(fr) else ""
            new = fault and v == r
            b += box(x, y, cw, rh, (REDF if new else "#fff"), "#CCC", 0, 1) + text(x + cw / 2, y + rh / 2, str(v), 9.6, weight="bold" if new else "normal", color=RED if new else INK)
        y = y0 + rh * 5 + 8
        b += text(x + cw / 2, y + 8, "F" if fault else "H", 9.6, weight="bold", color=RED if fault else GREEN)
    for s in range(4):
        b += text(x0 - 6, y0 + rh * (s + 1) + 4 + rh / 2, f"F{s + 1}", 9, anchor="end", color=GREY)
    yb = y0 + rh * 5 + 34
    hits = len(REFS) - faults
    b += text(180, yb, f"Page faults = {faults}    Hits = {hits}".replace("  ", "\u00a0\u00a0"), 11, weight="bold", color=P)
    b += text(180, yb + 18, f"Fault rate = {faults}/12 = {faults / 12 * 100:.1f}%   Hit ratio = {hits}/12 = {hits / 12 * 100:.1f}%".replace("  ", "\u00a0\u00a0"), 9.4, color=GREY)
    rule = ("FIFO: replace the page that came in first (oldest).", "LRU: replace the page not used for the longest time.")[algo == "lru"]
    b += note(12, yb + 30, 336, ["Reference string 1,2,3,4,5,1,3,1,6,3,2,3; 4 frames.", rule, "Red = page loaded by a page fault (F); H = hit."], size=9.6)
    return svg(360, yb + 88, b)



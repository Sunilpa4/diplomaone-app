VIVA = [
    G("Basics, Anomalies and Keys", [
        VE("What is normalization?", "The process of organizing tables and columns to reduce redundancy and remove insertion, update and deletion anomalies, by decomposing large tables into smaller related tables."),
        VE("Who introduced normalization?", "Dr. E. F. Codd, the father of the relational model."),
        VE("What is data redundancy?", "Storing the same data more than once in a database."),
        VE("Name the three anomalies.", "Insertion anomaly, update (modification) anomaly and deletion anomaly."),
        VE("What is an insertion anomaly?", "Some data cannot be inserted without other unrelated data, e.g. a new course cannot be added until a student joins it."),
        VE("What is an update anomaly?", "The same fact is stored in many rows; if one copy is not updated, the data becomes inconsistent."),
        VE("What is a deletion anomaly?", "Deleting one fact unintentionally removes another, e.g. deleting the last student of a course also loses the course details."),
        VE("What is a candidate key?", "A minimal super key: a set of attributes that uniquely identifies rows, with no unnecessary attribute."),
        VE("What is the difference between a super key and a candidate key?", "Every candidate key is a super key, but a super key may contain extra attributes. A candidate key is minimal."),
        VE("What is a composite key?", "A key made of two or more attributes, e.g. (ROLL, CID)."),
        VE("What is a prime attribute?", "An attribute that is part of at least one candidate key. Others are non-prime attributes."),
    ]),
    G("Functional Dependency", [
        VE("What is a functional dependency?", "X → Y means that the value of X uniquely determines the value of Y: rows with the same X always have the same Y."),
        VE("In X → Y, what are X and Y called?", "X is the determinant and Y is the dependent."),
        VE("What is a trivial functional dependency?", "X → Y where Y is a subset of X, e.g. {ROLL, NAME} → ROLL."),
        VE("What is a full functional dependency?", "Y depends on the whole composite key X and not on any part of it, e.g. (ROLL, CID) → MARKS."),
        VE("What is a partial dependency?", "A non-prime attribute depends on only part of a composite candidate key, e.g. ROLL → NAME when the key is (ROLL, CID)."),
        VE("What is a transitive dependency?", "If X → Y and Y → Z, where Y is non-key, then Z depends on X transitively, e.g. EMPNO → DEPTNO → DNAME."),
        VE("State Armstrong's three basic axioms.", "Reflexivity (if Y ⊆ X then X → Y), augmentation (if X → Y then XZ → YZ) and transitivity (if X → Y and Y → Z then X → Z)."),
        VE("What is attribute closure?", "X<sup>+</sup> is the set of all attributes that can be determined from X using the given FDs."),
        VE("How do you find whether X is a super key?", "Compute X<sup>+</sup>; if it contains all attributes of the relation, X is a super key."),
    ]),
    G("Normal Forms", [
        VE("What is a normal form?", "A set of rules (conditions) a relation must satisfy to reduce redundancy and anomalies."),
        VE("Define 1NF.", "A relation is in 1NF if every attribute holds only atomic (single) values and there are no repeating groups."),
        VE("Define 2NF.", "A relation is in 2NF if it is in 1NF and has no partial dependency: every non-prime attribute fully depends on the whole key."),
        VE("Define 3NF.", "A relation is in 3NF if it is in 2NF and has no transitive dependency of a non-prime attribute on the key."),
        VE("Define BCNF.", "A relation is in BCNF if, for every non-trivial FD X → Y, X is a super key (every determinant is a candidate key)."),
        VE("When is a 1NF table automatically in 2NF?", "When every candidate key has only one attribute, because a partial dependency needs a composite key."),
        VE("Is every 3NF relation in BCNF?", "No. Every BCNF relation is in 3NF, but a 3NF relation may have a determinant that is not a key (for a prime attribute)."),
        VE("Which normal form is usually enough in practice?", "3NF (sometimes BCNF)."),
        VE("What is UNF?", "Unnormalized form: a table with repeating groups or multi-valued cells."),
        VE("How is a table normalized?", "By decomposition: splitting a table that breaks a rule into smaller tables, each with its own primary key, linked by foreign keys."),
    ]),
    G("Advantages, Decomposition and Denormalization", [
        VE("Give two advantages of normalization.", "Less redundancy (saves space) and no anomalies (consistent data)."),
        VE("Give two disadvantages of normalization.", "More tables, and more joins are needed in queries, which can slow down reports."),
        VE("What is lossless-join decomposition?", "A decomposition in which joining the smaller tables gives back exactly the original table, with no lost or extra rows."),
        VE("How do you test that a decomposition into R1 and R2 is lossless?", "The common attributes of R1 and R2 must be a key of R1 or of R2."),
        VE("What is dependency preservation?", "Every original FD can be checked within the decomposed tables without joining them."),
        VE("What is denormalization?", "Deliberately adding controlled redundancy to a normalized database to make queries faster."),
        VE("Where is denormalization used?", "In reporting systems and data warehouses (OLAP), where reads are much more frequent than updates."),
    ]),
]

